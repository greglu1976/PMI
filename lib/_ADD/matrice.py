def get_matrix(group, compensation=False):
    """
    Возвращает матрицу преобразования для заданной группы соединений
    :param group: номер группы (0-11)
    :param compensation: флаг компенсации токов 3I0
    :return: соответствующая матрица numpy array
    """
    if compensation:
        return M0_matrices.get(group % 12, None)
    else:
        return M_matrices.get(group % 12, None)

def get_winding_groups(group, compensation=False):
    """
    Возвращает возможные группы соединений обмоток для заданной группы
    :param group: номер группы (0-11)
    :param compensation: флаг компенсации токов 3I0
    :return: список групп соединений
    """
    key = 'with_compensation' if compensation else 'no_compensation'
    return winding_groups[key].get(group % 12, [])